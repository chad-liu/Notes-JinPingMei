def survey() -> tuple[dict[str, int], dict[str, list[int]]]:
    """統計每個標記的出現次數與所在章回。已套用的字改數該字本身。"""
    data = json.loads((BUILD / "chapters.json").read_text(encoding="utf-8"))
    counts: dict[str, int] = defaultdict(int)
    chapters: dict[str, set[int]] = defaultdict(set)
    applied = {glyph: marker for marker, glyph, _, _ in APPLIED}
    for ch in data["chapters"]:
        for para in ch["paragraphs"]:
            for marker in re.findall(r"［[^］]*］", para["text"]):
                counts[marker] += 1
                chapters[marker].add(ch["n"])
            for glyph, marker in applied.items():
                n = para["text"].count(glyph)
                if n:
                    counts[marker] += n
                    chapters[marker].add(ch["n"])
    return counts, {k: sorted(v) for k, v in chapters.items()}


def main() -> None:
    counts, chapters = survey()
    listed = {m for _, rows in SECTIONS for m, *_ in rows}
    missing = set(counts) - listed
    unused = listed - set(counts)
    if missing or unused:
        print(f"注意：清單未收 {sorted(missing)}；清單多出 {sorted(unused)}")

    total_kinds = len(listed)
    total_hits = sum(counts.get(m, 0) for m in listed)
    lines = [
        "《金瓶梅》崇禎本缺字標記 ─ Unicode 對應字考訂清單",
        "=" * 72,
        "",
        "底本（books/金瓶梅(崇禎本).epub）輸入時，凡國標碼表所缺的漢字，",
        "一律以「［偏旁 部件］」註明。全書共 "
        f"{total_kinds} 種、{total_hits} 處。",
        "",
        "考訂依據：",
        "  詞話  以 books/ 的梅節夢梅館校本《金瓶梅詞話》平行段落比對而得",
        "  構字  標記所述偏旁部件與該 Unicode 字完全相符，且辭例可通",
        "  待考  詞話本該處亦無字，或所述構字在 Unicode 查無對應字位",
        "",
        "欄位：標記 / 對應字 / 碼位 / 次數 / 依據 / 章回 / 說明",
        "",
    ]

    for title, rows in SECTIONS:
        hits = sum(counts.get(m, 0) for m, *_ in rows)
        lines += [f"{title}（{len(rows)} 種、{hits} 處）", "-" * 72]
        for marker, glyph, basis, note in sorted(
                rows, key=lambda r: (-counts.get(r[0], 0), r[0])):
            code = f"U+{ord(glyph):04X}" if glyph else "－"
            chs = chapters.get(marker, [])
            span = ("第 " + "、".join(str(c) for c in chs) + " 回" if len(chs) <= 8
                    else f"第 {chs[0]}–{chs[-1]} 回中的 {len(chs)} 回")
            lines.append(f"{marker}\t{glyph or '－'}\t{code}\t"
                         f"{counts.get(marker, 0)} 處\t{basis}\t{span}\t{note}")
        lines.append("")

    lines += [
        "附註",
        "-" * 72,
        "1. 第三類列的是通行本用字，不是崇禎本原刻的那個字形。要照原刻存真，",
        "   目前只能維持「［　］」標記；要可讀，就改用通行字。兩者取捨由使用者決定。",
        "2. 第50回有一個沒有對應左括號的孤立「］」（「大雞巴］達達」），",
        "   是底本輸入時的訛誤，本站未改動，保留原樣。",
        "3. 已套用的對照表在 tools/extract_text.py 的 MISSING_GLYPHS；",
        "   在該表補上一行、重跑 extract_text.py 與 build_data.py 即可生效。",
        "4. 比對用的腳本為 tools/resolve_glyphs.py，本清單由 "
        "tools/write_glyph_list.py 產生。",
        "",
    ]

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"-> {OUT}　{total_kinds} 種、{total_hits} 處")
    for title, rows in SECTIONS:
        print(f"   {title}：{len(rows)} 種、"
              f"{sum(counts.get(m, 0) for m, *_ in rows)} 處")


if __name__ == "__main__":
    main()
