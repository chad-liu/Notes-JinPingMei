def survey() -> tuple[dict[str, int], dict[str, list[int]]]:
    """統計每個標記的出現次數與所在章回。

    刻意關掉 MISSING_GLYPHS 重新解析一次——不能改數還原後的字，
    因為有些字（如「搊」）原文本來就有，數字會多算。
    """
    import extract_text

    saved = extract_text.MISSING_GLYPHS
    extract_text.MISSING_GLYPHS = {}
    try:
        chapters = extract_text.parse_chapters()
    finally:
        extract_text.MISSING_GLYPHS = saved

    counts: dict[str, int] = defaultdict(int)
    chapter_set: dict[str, set[int]] = defaultdict(set)
    for ch in chapters:
        for para in ch["paragraphs"]:
            for marker in re.findall(r"［[^］]*］", para["text"]):
                counts[marker] += 1
                chapter_set[marker].add(ch["n"])
    return counts, {k: sorted(v) for k, v in chapter_set.items()}


def main() -> None:
    counts, chapters = survey()
    listed = {m for _, rows in SECTIONS for m, *_ in rows}
    missing = set(counts) - listed
    unused = listed - set(counts)
    if missing or unused:
        print(f"注意：清單未收 {sorted(missing)}；清單多出 {sorted(unused)}")

    total_kinds = len(listed)
    total_hits = sum(counts.get(m, 0) for m in listed)
    lines = [
        "《金瓶梅》崇禎本缺字標記 ─ Unicode 對應字考訂清單",
        "=" * 76,
        "",
        "底本（books/金瓶梅(崇禎本).epub）輸入時，凡國標碼表所缺的漢字，",
        f"一律以「［偏旁 部件］」註明。全書共 {total_kinds} 種、{total_hits} 處。",
        "",
        "考訂依據：",
        "  構字  用 CJK IDS 部件資料庫（88,937 字）反查，字形與原註完全相符",
        "  詞話  以梅節夢梅館校本《金瓶梅詞話》平行段落比對而得",
        "  辭例  由上下文的成詞、典故判定",
        "",
        "第二類另以 ctext 的《金瓶梅第一奇書》（崇禎本系統）交叉印證：",
        "該本把缺字逐一標成「●缺字：左「糸」右「堂」」這種形式，標缺字之處與本表一致。",
        "",
        "欄位：標記 / 用字 / 碼位 / 對照 / 次數 / 依據 / 章回 / 說明",
        "　　　第一類的「對照」欄記通行本寫法，第二三類記原刻的構字。",
        "",
    ]

    for title, rows in SECTIONS:
        hits = sum(counts.get(m, 0) for m, *_ in rows)
        lines += [f"{title}（{len(rows)} 種、{hits} 處）", "-" * 76]
        for marker, glyph, common, basis, note in sorted(
                rows, key=lambda r: (-counts.get(r[0], 0), r[0])):
            code = f"U+{ord(glyph):04X}" if glyph else "－"
            chs = chapters.get(marker, [])
            span = ("第 " + "、".join(str(c) for c in chs) + " 回" if len(chs) <= 8
                    else f"第 {chs[0]}–{chs[-1]} 回中的 {len(chs)} 回")
            lines.append(f"{marker}\t{glyph or '－'}\t{code}\t{common or '－'}\t"
                         f"{counts.get(marker, 0)} 處\t{basis}\t{span}\t{note}")
        lines.append("")

    lines += [
        "附註",
        "-" * 76,
        "1. 第一類取的是崇禎本原刻的字形；「對照」欄若有字，是通行本的另一種寫法",
        "   （如 𫄉綢／潞綢、𧤀角／犄角），檢索時可兩者並試。",
        "2. 第二類的原刻字形整個 IDS 資料庫都查不到，正文改用通行字，",
        "   「對照」欄記下原註的構字以便回溯。這一類不等於原刻的字形。",
        "3. 第三類連通行字都還沒定，正文維持「［　］」標記原樣。",
        "4. 「𢵞」「𨴃」「𧜽」這類字在 BMP 之外，JavaScript 以兩個碼元計算，",
        "   build_data.py 會把實體位移換算成 UTF-16 之後再輸出。",
        "5. 第50回有一個沒有對應左括號的孤立「］」（「大雞巴］達達」），",
        "   是底本輸入時的訛誤，本站未改動，保留原樣。",
        "6. 相關腳本：tools/ids_lookup.py（構字反查）、tools/resolve_glyphs.py（詞話比對）、",
        "   tools/write_glyph_list.py（產生本清單）。",
        "",
    ]

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"-> {OUT}　{total_kinds} 種、{total_hits} 處")
    for title, rows in SECTIONS:
        print(f"   {title}：{len(rows)} 種、"
              f"{sum(counts.get(m, 0) for m, *_ in rows)} 處")


